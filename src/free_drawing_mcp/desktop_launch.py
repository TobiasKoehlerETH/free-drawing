"""Open a generated drawing on its TechDraw sheet in the FreeCAD GUI."""

from __future__ import annotations

import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import textwrap

from .backends import detect_freecadcmd


def detect_freecad_gui() -> Path | None:
    """Find the GUI, preferring an explicit FREECAD_GUI installation."""
    configured = os.environ.get("FREECAD_GUI")
    if configured:
        path = Path(configured).expanduser()
        return path.resolve() if path.is_file() else None

    command = detect_freecadcmd()
    if command:
        parent = Path(command[0]).parent
        for name in ("FreeCAD.exe", "freecad.exe", "FreeCAD", "freecad"):
            path = parent / name
            if path.is_file():
                return path.resolve()

    for name in ("FreeCAD", "freecad", "FreeCAD.exe", "freecad.exe"):
        executable = shutil.which(name)
        if executable:
            return Path(executable).resolve()

    for root in (
        os.environ.get("ProgramFiles", r"C:\Program Files"),
        os.environ.get("LOCALAPPDATA", ""),
    ):
        if not root:
            continue
        for install in sorted(Path(root).glob("FreeCAD*"), reverse=True):
            for name in ("FreeCAD.exe", "freecad.exe"):
                path = install / "bin" / name
                if path.is_file():
                    return path.resolve()

    for path in (
        Path("/Applications/FreeCAD.app/Contents/MacOS/FreeCAD"),
        Path("/usr/bin/freecad"),
    ):
        if path.is_file():
            return path
    return None


def _opening_macro(document: Path, status: Path) -> str:
    # Python literals escape quotes, backslashes, newlines and Unicode safely.
    return textwrap.dedent(f'''\
        # Generated by Free Drawing. Opens the drawing without saving it.
        import json
        import traceback
        from pathlib import Path
        import FreeCAD as App
        import FreeCADGui as Gui
        from PySide import QtCore

        def _free_drawing_open():
            document_path = {str(document)!r}
            status_path = Path({str(status)!r})

            def report(result):
                status_path.write_text(json.dumps(result, ensure_ascii=False), encoding="utf-8")

            try:
                doc = App.openDocument(document_path)
                pages = [obj for obj in doc.Objects if obj.TypeId == "TechDraw::DrawPage"]
                if not pages:
                    raise RuntimeError("This document does not contain a TechDraw drawing page.")
                page = pages[0]
                App.setActiveDocument(doc.Name)
                Gui.activateWorkbench("TechDrawWorkbench")
                doc.recompute()

                def show_page():
                    try:
                        App.setActiveDocument(doc.Name)
                        page.ViewObject.show()
                        active = Gui.getDocument(doc.Name).activeView()
                        if type(active).__name__ != "MDIViewPagePy":
                            raise RuntimeError("FreeCAD did not activate the TechDraw drawing page.")
                        active.fitAll()
                        Gui.updateGui()
                        report({{"opened": True, "document": document_path,
                                "page": page.Name, "active_view_type": str(type(active))}})
                    except Exception:
                        report({{"opened": False, "error": traceback.format_exc()}})

                QtCore.QTimer.singleShot(0, show_page)
            except Exception:
                report({{"opened": False, "error": traceback.format_exc()}})

        _free_drawing_open()
        del _free_drawing_open
        ''')


def open_in_freecad(document: Path, executable: Path | None = None) -> subprocess.Popen:
    """Launch FreeCAD and show the first TechDraw sheet of an existing FCStd.

    The generated macro and its JSON result stay next to the drawing. They make
    an opening failure diagnosable without changing the FCStd or input model.
    """
    document = Path(document).expanduser().resolve(strict=True)
    if not document.is_file() or document.suffix.lower() != ".fcstd":
        raise ValueError("Choose an existing FreeCAD drawing (.FCStd).")
    executable = Path(executable) if executable is not None else detect_freecad_gui()
    if executable is None or not executable.is_file():
        raise FileNotFoundError("FreeCAD was not found. Install FreeCAD or set FREECAD_GUI to its executable.")
    executable = executable.resolve()
    with tempfile.NamedTemporaryFile(
        mode="w", encoding="utf-8", prefix=".free-drawing-open-", suffix=".FCMacro",
        dir=document.parent, delete=False,
    ) as stream:
        macro = Path(stream.name)
        stream.write(_opening_macro(document, macro.with_suffix(".json")))
    environment = os.environ.copy()
    # Headless generation and Qt-based launchers can otherwise direct FreeCAD
    # to an offscreen display or an incompatible Python Qt plugin directory.
    if environment.get("QT_QPA_PLATFORM") in {"offscreen", "minimal"}:
        environment.pop("QT_QPA_PLATFORM")
    environment.pop("QT_PLUGIN_PATH", None)
    environment.pop("QT_QPA_PLATFORM_PLUGIN_PATH", None)
    return subprocess.Popen(
        [str(executable), str(macro)], shell=False, cwd=document.parent,
        env=environment,
        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
